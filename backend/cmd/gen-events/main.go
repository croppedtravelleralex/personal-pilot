func generateTSListeners() string {
	var b strings.Builder
	b.WriteString("// Auto-generated by backend/cmd/gen-events. DO NOT EDIT.\n")
	b.WriteString("// Type-safe listener hooks for all registered events.\n")
	b.WriteString("// Usage:\n")
	b.WriteString("//   import { onAccountLoginSuccess } from '@wails/events';\n")
	b.WriteString("//   const unsub = onAccountLoginSuccess((payload) => { ... });\n")
	b.WriteString("//   // later: unsub();\n\n")
	b.WriteString("import { EventsOn } from '../../runtime/runtime';\n")
	b.WriteString("import type { EventName, EventPayloadMap } from './gen_types';\n\n")

	allNames := events.AllRegistryNames()
	sort.Strings(allNames)

	for _, name := range allNames {
		def := events.Registry[name]
		funcName := eventNameToTSListenerFn(name)
		if len(def.Payload) == 0 {
			b.WriteString(fmt.Sprintf(
				"/** %s */\nexport function %s(handler: () => void): () => void {\n  return EventsOn('%s', handler);\n}\n\n",
				def.Description, funcName, name,
			))
		} else {
			b.WriteString(fmt.Sprintf(
				"/** %s */\nexport function %s(handler: (payload: EventPayloadMap['%s']) => void): () => void {\n  return EventsOn('%s', handler);\n}\n\n",
				def.Description, funcName, name, name,
			))
		}
	}

	// Generic typed listener
	b.WriteString("// TypedOn is a generic listener that infers payload from the event name.\n")
	b.WriteString("export function TypedOn<N extends EventName>(\n")
	b.WriteString("  eventName: N,\n")
	b.WriteString("  handler: (payload: EventPayloadMap[N]) => void\n")
	b.WriteString("): () => void {\n")
	b.WriteString("  return EventsOn(eventName, handler as (payload: unknown) => void);\n")
	b.WriteString("}\n")

	return b.String()
}

func generateYAMLSchema() string {
	var b strings.Builder
	b.WriteString("# Auto-generated by backend/cmd/gen-events. DO NOT EDIT.\n")
	b.WriteString("# Source: backend/internal/events/registry.go\n\n")

	byNS := events.RegistryNamesByNamespace()
	namespaces := make([]string, 0, len(byNS))
	for ns := range byNS {
		namespaces = append(namespaces, ns)
	}
	sort.Strings(namespaces)

	b.WriteString("namespaces:\n")
	for _, ns := range namespaces {
		names := byNS[ns]
		sort.Strings(names)
		b.WriteString(fmt.Sprintf("  %s:\n", ns))
		b.WriteString("    events:\n")
		for _, name := range names {
			def := events.Registry[name]
			b.WriteString(fmt.Sprintf("      - name: \"%s\"\n", name))
			b.WriteString(fmt.Sprintf("        description: \"%s\"\n", def.Description))
			b.WriteString(fmt.Sprintf("        severity: \"%s\"\n", def.Severity))
			if len(def.Payload) > 0 {
				b.WriteString("        payload:\n")
				for _, f := range def.Payload {
					req := ""
					if f.Required {
						req = " (required)"
					}
					b.WriteString(fmt.Sprintf("          - field: \"%s\"\n", f.Name))
					b.WriteString(fmt.Sprintf("            type: \"%s\"%s\n", f.Type, req))
				}
			}
		}
	}
	return b.String()
}

func generateGoEmitters() string {
	var b strings.Builder
	b.WriteString("// Code generated by backend/cmd/gen-events. DO NOT EDIT.\n")
	b.WriteString("// Source: backend/internal/events/registry.go\n\n")
	b.WriteString("package events\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"context\"\n")
	b.WriteString("\t\"encoding/json\"\n")
	b.WriteString(")\n\n")

	allNames := events.AllRegistryNames()
	sort.Strings(allNames)

	// Track generated struct names to avoid duplicates
	generatedStructs := make(map[string]bool)

	// Generate payload structs
	b.WriteString("// ─── Payload Types ──────────────────────────────────────────────\n\n")
	for _, name := range allNames {
		def := events.Registry[name]
		if len(def.Payload) == 0 {
			continue
		}
		structName := eventNameToTSIface(name) + "Payload"
		if generatedStructs[structName] {
			continue
		}
		generatedStructs[structName] = true

		b.WriteString(fmt.Sprintf("// %s is the payload for event \"%s\".\n", structName, name))
		b.WriteString(fmt.Sprintf("type %s struct {\n", structName))
		for _, field := range def.Payload {
			goField := camelToPascal(field.Name)
			goType := eventFieldGoType(field.Type)
			b.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", goField, goType, field.Name))
		}
		b.WriteString("}\n\n")
	}

	// Generate Emit functions
	b.WriteString("// ─── Emitter Functions ──────────────────────────────────────────\n\n")
	b.WriteString("// toMap converts a struct to map[string]interface{} via JSON round-trip.\n")
	b.WriteString("func toMap(v interface{}) map[string]interface{} {\n")
	b.WriteString("\tdata, _ := json.Marshal(v)\n")
	b.WriteString("\tvar result map[string]interface{}\n")
	b.WriteString("\t_ = json.Unmarshal(data, &result)\n")
	b.WriteString("\treturn result\n")
	b.WriteString("}\n\n")

	for _, name := range allNames {
		def := events.Registry[name]
		funcName := "Emit" + eventNameToTSIface(name)

		b.WriteString(fmt.Sprintf("// %s emits a \"%s\" event.\n", funcName, name))
		b.WriteString(fmt.Sprintf("// %s\n", def.Description))

		if len(def.Payload) == 0 {
			b.WriteString(fmt.Sprintf(
				"func %s(ctx context.Context) {\n\tEmitAndLog(ctx, %s)\n}\n\n",
				funcName, eventConstName(name),
			))
		} else {
			structName := eventNameToTSIface(name) + "Payload"
			b.WriteString(fmt.Sprintf(
				"func %s(ctx context.Context, data %s) {\n\tEmitAndLog(ctx, %s, toMap(data))\n}\n\n",
				funcName, structName, eventConstName(name),
			))
		}
	}

	return b.String()
}

func eventNameToTSListenerFn(name string) string {
	return "on" + eventNameToTSIface(name)
}

func eventNameToTSIface(name string) string {
	parts := strings.Split(name, ":")
	var result strings.Builder
	for _, part := range parts {
		for _, segment := range strings.Split(part, "-") {
			if len(segment) > 0 {
				result.WriteString(strings.ToUpper(segment[:1]))
				result.WriteString(segment[1:])
			}
		}
	}
	return result.String()
}

func eventNameToGoConst(name string) string {
	return "Event" + eventNameToTSIface(name)
}

func goTypeToTS(goType string) string {
	switch goType {
	case "string":
		return "string"
	case "int", "int32", "int64", "float64":
		return "number"
	case "bool":
		return "boolean"
	case "[]string":
		return "string[]"
	case "map[string]interface{}":
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}

// camelToPascal converts "profileId" → "ProfileId", "debugPort" → "DebugPort"
func camelToPascal(s string) string {
	if len(s) == 0 {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// eventFieldGoType maps registry field types to Go types.
func eventFieldGoType(t string) string {
	switch t {
	case "string":
		return "string"
	case "int":
		return "int"
	case "int64":
		return "int64"
	case "float64":
		return "float64"
	case "bool":
		return "bool"
	case "[]string":
		return "[]string"
	case "map[string]interface{}":
		return "map[string]interface{}"
	default:
		return "interface{}"
	}
}

// eventConstName returns the Go constant name for an event.
// It checks the manually-defined constants first, falling back to auto-generation.
func eventConstName(name string) string {
	if cn, ok := manualEventConstants[name]; ok {
		return cn
	}
	return eventNameToGoConst(name)
}

