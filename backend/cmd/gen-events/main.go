package main

import (
	"ant-chrome/backend/internal/events"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	projRoot := findProjectRoot()

	// Generate TypeScript types
	tsPath := filepath.Join(projRoot, "frontend", "src", "wailsjs", "go", "events", "gen_types.ts")
	if err := os.MkdirAll(filepath.Dir(tsPath), 0755); err != nil {
		fmt.Fprintf(os.Stderr, "create dir: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(tsPath, []byte(generateTSTypes()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write ts types: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("Generated:", tsPath)

	// Generate event documentation
	docPath := filepath.Join(projRoot, "EVENTS.md")
	if err := os.WriteFile(docPath, []byte(generateDocs()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write docs: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("Generated:", docPath)

	// Generate Go constants for new events (those without constants yet)
	goConstPath := filepath.Join(projRoot, "backend", "internal", "events", "gen_constants.go")
	if err := os.WriteFile(goConstPath, []byte(generateGoConstants()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write go constants: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("Generated:", goConstPath)

	// Generate TypeScript listener hooks
	listenersPath := filepath.Join(projRoot, "frontend", "src", "wailsjs", "go", "events", "gen_listeners.ts")
	if err := os.WriteFile(listenersPath, []byte(generateTSListeners()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write ts listeners: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("Generated:", listenersPath)

	// Generate YAML schema
	schemaPath := filepath.Join(projRoot, "backend", "internal", "events", "schema.yaml")
	if err := os.WriteFile(schemaPath, []byte(generateYAMLSchema()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write yaml schema: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("Generated:", schemaPath)

	// Generate Go type-safe emitter functions
	emittersPath := filepath.Join(projRoot, "backend", "internal", "events", "gen_emitters.go")
	if err := os.WriteFile(emittersPath, []byte(generateGoEmitters()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write go emitters: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("Generated:", emittersPath)
}

func findProjectRoot() string {
	dir, _ := os.Getwd()
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}

func generateTSTypes() string {
	var b strings.Builder
	b.WriteString("// Auto-generated by backend/cmd/gen-events. DO NOT EDIT.\n")
	b.WriteString("// Source: backend/internal/events/registry.go\n\n")

	byNS := events.RegistryNamesByNamespace()
	namespaces := make([]string, 0, len(byNS))
	for ns := range byNS {
		namespaces = append(namespaces, ns)
	}
	sort.Strings(namespaces)

	b.WriteString("// EventName is the union of all known event name strings.\n")
	b.WriteString("export type EventName =\n")
	allNames := events.AllRegistryNames()
	sort.Strings(allNames)
	for i, name := range allNames {
		sep := " |"
		if i == len(allNames)-1 {
			sep = ";"
		}
		b.WriteString(fmt.Sprintf("  '%s'%s\n", name, sep))
	}
	b.WriteString("\n")

	for _, ns := range namespaces {
		names := byNS[ns]
		sort.Strings(names)

		b.WriteString(fmt.Sprintf("// ─── %s ──────────────────────────────────────────────\n", strings.ToUpper(ns)))

		for _, name := range names {
			def := events.Registry[name]
			if len(def.Payload) == 0 {
				continue
			}

			ifaceName := eventNameToTSIface(name) + "Payload"
			b.WriteString(fmt.Sprintf("export interface %s {\n", ifaceName))
			for _, field := range def.Payload {
				optional := ""
				if !field.Required {
					optional = "?"
				}
				tsType := goTypeToTS(field.Type)
				b.WriteString(fmt.Sprintf("  %s%s: %s;\n", field.Name, optional, tsType))
			}
			b.WriteString("}\n\n")
		}
	}

	b.WriteString("// EventPayloadMap maps each event name to its payload type.\n")
	b.WriteString("export type EventPayloadMap = {\n")
	for _, name := range allNames {
		def := events.Registry[name]
		if len(def.Payload) == 0 {
			b.WriteString(fmt.Sprintf("  '%s': Record<string, never>;\n", name))
		} else {
			b.WriteString(fmt.Sprintf("  '%s': %sPayload;\n", name, eventNameToTSIface(name)))
		}
	}
	b.WriteString("};\n\n")

	b.WriteString("// TypedEventPayload extracts the payload type for a given event name.\n")
	b.WriteString("export type TypedEventPayload<N extends EventName> = EventPayloadMap[N];\n")

	return b.String()
}

func generateDocs() string {
	var b strings.Builder
	b.WriteString("# Ant Browser Events Reference\n\n")
	b.WriteString("> Auto-generated by `backend/cmd/gen-events`. DO NOT EDIT.\n\n")
	b.WriteString(fmt.Sprintf("**Total events:** %d\n\n", len(events.Registry)))

	byNS := events.RegistryNamesByNamespace()
	namespaces := make([]string, 0, len(byNS))
	for ns := range byNS {
		namespaces = append(namespaces, ns)
	}
	sort.Strings(namespaces)

	b.WriteString("## Table of Contents\n\n")
	for _, ns := range namespaces {
		names := byNS[ns]
		b.WriteString(fmt.Sprintf("- [%s](#%s) (%d events)\n", ns, ns, len(names)))
	}
	b.WriteString("\n")

	severityIcon := func(s string) string {
		switch s {
		case "critical":
			return "🔴"
		case "error":
			return "🟠"
		case "warn":
			return "🟡"
		case "info":
			return "🔵"
		default:
			return "⚪"
		}
	}

	for _, ns := range namespaces {
		names := byNS[ns]
		sort.Strings(names)

		b.WriteString(fmt.Sprintf("## %s\n\n", ns))
		b.WriteString("| Event | Severity | Description | Payload |\n")
		b.WriteString("|-------|----------|-------------|--------|\n")

		for _, name := range names {
			def := events.Registry[name]
			sev := severityIcon(def.Severity) + " " + def.Severity
			payloadDesc := "-"
			if len(def.Payload) > 0 {
				var fields []string
				for _, f := range def.Payload {
					req := ""
					if f.Required {
						req = "*"
					}
					fields = append(fields, fmt.Sprintf("`%s` (%s)%s", f.Name, f.Type, req))
				}
				payloadDesc = strings.Join(fields, ", ")
			}
			b.WriteString(fmt.Sprintf("| `%s` | %s | %s | %s |\n", name, sev, def.Description, payloadDesc))
		}
		b.WriteString("\n")
	}

	return b.String()
}

